const COLORS = {
    I: 'cyan',
    O: 'yellow',
    T: 'purple',
    S: 'green',
    Z: 'red',
    J: 'blue',
    L: 'orange'
};

class Piece{
    constructor(type, x=3, y=0){
        this.type = type;
        this.x = x;
        this.y = y;
        this.rotation = 0;
        this.color = COLORS[type];
    }

    getShape(){
        return SHAPES[this.type][this.rotation]
    }

    rotate(){
        this.rotation = (this.rotation + 1) % 4
    }
}

export default Piece;